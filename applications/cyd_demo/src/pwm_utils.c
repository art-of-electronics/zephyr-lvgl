#include <errno.h>
#include <stddef.h>
#include <stdint.h>

#include <pwm_utils.h>


/*****************************************************************************
                          PRIVATE DEFINES / MACROS
*****************************************************************************/
#define PWM_PERCENT_MAX (100U)

/*****************************************************************************
                     PRIVATE STRUCTS / ENUMS / VARIABLES
*****************************************************************************/

/*****************************************************************************
                         PRIVATE FUNCTION DECLARATIONS
*****************************************************************************/

/*****************************************************************************
                       PRIVATE FUNCTION IMPLEMENTATIONS
*****************************************************************************/

/*****************************************************************************
                           INTERFACE IMPLEMENTATION
*****************************************************************************/
int pwm_set_percent(const struct pwm_dt_spec *pwm, uint32_t percent)
{
    uint64_t pulse = 0U;

    if ((NULL == pwm) || (PWM_PERCENT_MAX < percent)) {
        return -EINVAL;
    }

    pulse = ((uint64_t)pwm->period * percent) / PWM_PERCENT_MAX;

    return pwm_set_dt(pwm, pwm->period, (uint32_t)pulse);
}
